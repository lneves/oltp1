package org.oltp1.runner.runtime;

import java.math.BigDecimal;
import java.math.RoundingMode;
import java.util.ArrayList;
import java.util.Collections;
import java.util.HashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import org.oltp1.runner.generator.CRandom;
import org.oltp1.runner.model.TickerEntry;
import org.oltp1.runner.model.TradeStatus;
import org.oltp1.runner.model.TradeType;
import org.oltp1.runner.tx.market_feed.TxMarketFeedInput;

/**
 * Builds Market-Feed batches from the Trade-Results the MEE has completed.
 *
 * <h2>Why the feed is driven by completed trades</h2>
 * TPC-E v1.14.0 specifies Market-Feed as an <em>event-driven</em> transaction, not a
 * periodic one:
 * <ul>
 * <li>Clause 6.3.1 (p. 215): "the number of Market-Feed Transactions is controlled by the
 * CMEE code to be <b>one for every ten Trade-Results generated</b>."</li>
 * <li>Clause 3.3.3 (p. 91): "Each Market-Feed ticker consists of 20 entries
 * (<code>max_feed_len</code> constant in TxnHarnessStructs.h). Ten of these entries are a
 * result of trades submitted to the MEE by this brokerage house. The remaining entries are
 * generated by the MEE to simulate the reporting of trades from other brokerage houses."</li>
 * <li>Clause 3.2.1.2 (p. 77): <code>max_feed_len = 20</code>.</li>
 * </ul>
 * The reference implementation follows this literally: {@code CMEETickerTape::AddToBatch}
 * flushes a Market-Feed only when the batch reaches 20 entries, there is no timer, and each
 * completed trade contributes one "real" entry plus (from
 * {@code CMEETickerTape::AddArtificialEntries}) up to one padding entry, because
 * {@code PaddingLimit = max_feed_len / 10 - 1 = 1}.
 *
 * <p>That means the ticker rate is proportional to achieved throughput &mdash; roughly
 * <em>2 entries per Trade-Result</em> &mdash; and not to elapsed time. An earlier version of
 * this emulator published a fixed batch every second regardless of workload, which made the
 * Market-Feed share of the mix a function of wall-clock time, starved the limit-order trigger
 * path, and made the reported total transaction rate <em>less</em> accurate the faster the
 * system under test was.
 *
 * <h2>Ratio arithmetic</h2>
 * {@link #ENTRIES_PER_COMPLETED_TRADE} is 2 (one real + one artificial), so a full batch is
 * exactly {@link #BATCH_SIZE / 2} = 10 completed trades. The 1 Market-Feed : 10 Trade-Result
 * ratio of Clause 6.3.1 is therefore an identity here, not an approximation, for every batch
 * that reaches its target size. Clause 3.3.3 also permits short batches ("The Market-Feed
 * Transaction is allowed to process any number of ticker elements (from one to all)"), which is
 * what a final flush at shutdown uses.
 *
 * <h2>Price model</h2>
 * Prices are moved by up to {@link #MAX_PRICE_CHANGE} and <em>reflected</em> at the edges of
 * the {@code [MIN_PRICE, MAX_PRICE]} band rather than clamped, so a price cannot get pinned to a
 * boundary and stop traversing the band. The band is the same {@code [20.00, 30.00]} the data
 * generator uses when it populates {@code LAST_TRADE}
 * ({@code org.oltp1.egen.generator.MEESecurity.MIN_SEC_PRICE}/{@code MAX_SEC_PRICE}, matching
 * {@code egen/inc/HoldingsAndTradesTable.h}), so the feed moves prices over the same range the
 * pre-populated history did. A price change is applied when an artificial entry is generated,
 * which happens once per completed trade.
 *
 * <h2>Concurrency</h2>
 * A {@code TickerFeed} instance is confined to the single ticker-feed thread, which owns the
 * mutable {@code lastPrice} state and the {@link CRandom}. The completed Trade-Results arrive
 * from the MEE result workers through a queue that {@link MarketExchangeEmulator} owns (the same
 * way it owns the trade-result queue), so this class contains no shared mutable state and needs
 * no synchronisation of its own. That is also why the instance is created inside the ticker
 * thread rather than in the emulator constructor.
 */
final class TickerFeed
{
	/** TPC-E {@code max_feed_len}: the maximum number of items on a Market-Feed ticker. */
	static final int BATCH_SIZE = 20;

	/**
	 * One real entry per completed Trade-Result, plus one artificial entry, matching
	 * {@code MEETickerTape}'s 10:10 split of {@code max_feed_len}.
	 */
	static final int ENTRIES_PER_COMPLETED_TRADE = 2;

	/** Completed Trade-Results that make up a full batch. */
	static final int TRADES_PER_BATCH = BATCH_SIZE / ENTRIES_PER_COMPLETED_TRADE;

	/**
	 * Quantity reported for an artificial ("other brokerage house") ticker entry. From
	 * {@code MEETickerTape::RANDOM_TRADE_QTY_1} / {@code _2}.
	 */
	private static final int ARTIFICIAL_TRADE_QTY_1 = 325;

	private static final int ARTIFICIAL_TRADE_QTY_2 = 425;

	/**
	 * Lower bound of the price band, in dollars. Matches
	 * {@code egen/inc/HoldingsAndTradesTable.h} ({@code fMinSecPrice = 20}) and
	 * {@code egen/src/MEESecurity.cpp}, and therefore the range the initial
	 * {@code LAST_TRADE} population was generated in.
	 */
	static final double MIN_PRICE = 20.00;

	/** Upper bound of the price band, in dollars. See {@link #MIN_PRICE}. */
	static final double MAX_PRICE = 30.00;

	/** Largest relative move applied to a security's price by one artificial entry. */
	private static final double MAX_PRICE_CHANGE = 0.20;

	/** Price granularity, matching the {@code LT_PRICE} scale. */
	private static final double PRICE_CHANGE_INCREMENT = 0.01;

	/**
	 * How long the feed may stay idle before the ticker thread publishes a purely artificial
	 * batch so that prices keep moving.
	 * <p>
	 * 30 s rather than the 10 s a first cut would suggest: a full batch needs
	 * {@link #TRADES_PER_BATCH} completed Trade-Results, so at 0.33 tpsE (and below) the natural
	 * cadence is already 30 s or slower and a 10 s fallback would fire in the middle of a healthy
	 * run, doubling the Market-Feed count and re-introducing the very distortion this class
	 * exists to remove. At 30 s the fallback only engages when the feed is genuinely starved
	 * &mdash; before the first Trade-Order of a run completes, or if the client pool stalls.
	 */
	static final long IDLE_TIMEOUT_MS = 30_000L;

	/** The same bound in nanoseconds, for the ticker loop's monotonic idle check. */
	static final long IDLE_TIMEOUT_NANOS = java.util.concurrent.TimeUnit.MILLISECONDS.toNanos(IDLE_TIMEOUT_MS);

	// Mutable state, confined to the ticker-feed thread.

	private final String[] symbols;

	private final double[] lastPrice;

	private final Map<String, Integer> symbolIndex;

	private final CRandom rnd;

	private long batchCount;

	private long entryCount;

	private long stallCount;

	/**
	 * A completed Trade-Result waiting to be turned into a ticker entry. Immutable, so it can
	 * cross the thread boundary between an MEE result worker and the ticker-feed thread safely.
	 */
	record CompletedTrade(String symbol, int quantity)
	{
	}

	/** A batch of ticker entries plus the distinct-symbol count the transaction requires. */
	record Batch(List<TickerEntry> entries, int uniqueSymbols)
	{
	}

	TickerFeed(String[] symbols, double[] lastPrice, CRandom rnd)
	{
		if (symbols.length == 0)
		{
			throw new IllegalArgumentException("ticker feed needs a non-empty security universe");
		}
		if (symbols.length != lastPrice.length)
		{
			throw new IllegalArgumentException("symbols and lastPrice must be the same length");
		}
		this.symbols = symbols;
		this.lastPrice = lastPrice;
		this.rnd = rnd;

		Map<String, Integer> index = new HashMap<>(symbols.length * 2);
		for (int i = 0; i < symbols.length; i++)
		{
			// LAST_TRADE has a primary key on lt_s_symb, so a duplicate is impossible; if one
			// ever appears the first index wins, which keeps lastPrice[] in step.
			index.putIfAbsent(symbols[i], i);
		}
		this.symbolIndex = index;
	}

	/**
	 * Builds one Market-Feed batch: two entries per completed Trade-Result, a real one reporting
	 * the trade at the security's current price and an artificial one that moves a randomly chosen
	 * security's price. Ticker-feed thread only.
	 */
	Batch buildBatch(List<CompletedTrade> trades)
	{
		List<TickerEntry> entries = new ArrayList<>(trades.size() * ENTRIES_PER_COMPLETED_TRADE);

		for (CompletedTrade trade : trades)
		{
			entries.add(new TickerEntry(trade.symbol(), money(currentPriceOf(trade.symbol())), trade.quantity()));
			entries.add(nextArtificialEntry());
		}

		return toBatch(entries);
	}

	/**
	 * A batch of nothing but artificial entries, published only when the feed has been idle for
	 * {@link #IDLE_TIMEOUT_MS} so that prices keep moving. Ticker-feed thread only.
	 */
	Batch buildIdleBatch()
	{
		stallCount++;

		List<TickerEntry> entries = new ArrayList<>(BATCH_SIZE);
		for (int i = 0; i < BATCH_SIZE; i++)
		{
			entries.add(nextArtificialEntry());
		}

		return toBatch(entries);
	}

	/** The market-feed input for a batch. The transaction checks the distinct-symbol count. */
	static TxMarketFeedInput toInput(Batch batch)
	{
		return new TxMarketFeedInput(
				TradeStatus.SUBMITTED,
				TradeType.LIMIT_BUY,
				TradeType.LIMIT_SELL,
				TradeType.STOP_LOSS,
				batch.entries(),
				batch.uniqueSymbols());
	}

	long batchCount()
	{
		return batchCount;
	}

	long entryCount()
	{
		return entryCount;
	}

	long idleBatchCount()
	{
		return stallCount;
	}

	// ------------------------------------------------------------------ //
	// Internals
	// ------------------------------------------------------------------ //

	private Batch toBatch(List<TickerEntry> entries)
	{
		// TxMarketFeed rolls the batch back unless the number of LAST_TRADE rows updated equals
		// the distinct-symbol count declared here, so this must be computed the same way the
		// transaction's own aggregateBySymbol() collapses the batch.
		int uniqueSymbols = new LinkedHashSet<>(entries.stream().map(TickerEntry::symbol).toList()).size();

		batchCount++;
		entryCount += entries.size();

		return new Batch(Collections.unmodifiableList(entries), uniqueSymbols);
	}

	/**
	 * One artificial entry: a randomly chosen security whose price is moved by up to
	 * {@link #MAX_PRICE_CHANGE}, reported with one of the two reference quantities.
	 */
	private TickerEntry nextArtificialEntry()
	{
		int ix = rnd.rndIntRange(0, symbols.length - 1);
		String symbol = symbols[ix];

		double change = rnd.rndDoubleIncrRange(-MAX_PRICE_CHANGE, MAX_PRICE_CHANGE, PRICE_CHANGE_INCREMENT);
		double price = reflect(lastPrice[ix] * (1.0 + change));
		lastPrice[ix] = price;

		int qty = rnd.rndPercent(50) ? ARTIFICIAL_TRADE_QTY_1 : ARTIFICIAL_TRADE_QTY_2;

		return new TickerEntry(symbol, money(price), qty);
	}

	/**
	 * The price this emulator last published for a symbol. Symbols that arrive from a
	 * Trade-Result but were filtered out of the universe (or, during a partitioned load, belong to
	 * another partition) fall back to the raw {@code LAST_TRADE} price the universe was seeded
	 * with, which is in the same band.
	 */
	private double currentPriceOf(String symbol)
	{
		Integer ix = symbolIndex.get(symbol);
		return (ix != null) ? lastPrice[ix] : MIN_PRICE;
	}

	private static double reflect(double price)
	{
		// Reflect rather than clamp: clamping would pin the price to a boundary and stop it
		// traversing the band, which is what drives the limit-order trigger path.
		double moved = (price > MAX_PRICE || price < MIN_PRICE)
				? (2.0 * (price > MAX_PRICE ? MAX_PRICE : MIN_PRICE)) - price
				: price;

		return round2(Math.min(MAX_PRICE, Math.max(MIN_PRICE, moved)));
	}

	/**
	 * The price as {@code LT_PRICE} would store it. The scale is pinned to 2 so the serialized
	 * ticker JSON always matches the {@code DECIMAL(10,2)} the dialects read it into, instead of
	 * inheriting whatever scale {@code BigDecimal.valueOf(double)} happens to produce
	 * ({@code BigDecimal.valueOf(20.0)} is "20.0", not "20.00").
	 */
	private static BigDecimal money(double price)
	{
		return BigDecimal.valueOf(price).setScale(2, RoundingMode.HALF_UP);
	}

	private static double round2(double value)
	{
		return BigDecimal.valueOf(value).setScale(2, RoundingMode.HALF_UP).doubleValue();
	}
}
